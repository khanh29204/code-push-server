let currentLang = localStorage.getItem('lang')
  || ((navigator.language || '').toLowerCase().startsWith('vi') ? 'vi' : 'en');

function t(key, ...args) {
  const dict = I18N[currentLang] || I18N.en;
  const v = dict[key] ?? I18N.en[key] ?? key;
  return typeof v === 'function' ? v(...args) : v;
}

function applyI18n(root = document) {
  root.querySelectorAll('[data-i18n]').forEach(el => {
    el.textContent = t(el.getAttribute('data-i18n'));
  });
  root.querySelectorAll('[data-i18n-title]').forEach(el => {
    el.setAttribute('title', t(el.getAttribute('data-i18n-title')));
  });
}

function setLang(lang) {
  currentLang = lang;
  localStorage.setItem('lang', lang);
  document.documentElement.lang = lang;
  document.getElementById('langLabel').textContent = lang === 'vi' ? 'VI' : 'EN';
  applyI18n();
  // Re-render dynamic bits
  if (typeof renderAppList === 'function') renderAppList();
  if (typeof renderDeploymentTabs === 'function') renderDeploymentTabs();
  if (typeof renderHistory === 'function') renderHistory();
}
